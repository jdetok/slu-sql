-- School of Med HOR23 SGBSTDN enrolled
SELECT RORALGS_AMT * rokmisc.F_CALC_STUD_BILL_HRS(:PERIOD, X.SGBSTDN_PIDM, 'N') as amt
FROM SGBSTDN X
INNER JOIN RORALGS on RORALGS_AIDY_CODE = :AIDY
    AND RORALGS_KEY_1 = 'PBDG'
    AND RORALGS_KEY_4 = '1TUI'
    AND RORALGS_KEY_5 = X.SGBSTDN_LEVL_CODE
    AND RORALGS_KEY_9 = X.SGBSTDN_PROGRAM_1
WHERE X.SGBSTDN_LEVL_CODE = 'GR'
AND X.SGBSTDN_COLL_CODE_1 = 'MD'
AND X.SGBSTDN_PROGRAM_1 = 'HOR23'
AND X.SGBSTDN_STST_CODE IN  ('AS','IL','P1')
AND X.SGBSTDN_TERM_CODE_EFF = (
    SELECT MAX(Y.SGBSTDN_TERM_CODE_EFF)
    FROM SGBSTDN Y
    WHERE Y.SGBSTDN_PIDM = X.SGBSTDN_PIDM
    AND Y.SGBSTDN_TERM_CODE_EFF <= :PERIOD
)
AND rokmisc.F_CALC_STUD_BILL_HRS(:PERIOD, X.SGBSTDN_PIDM, 'N') > 0
AND X.SGBSTDN_PIDM = :PIDM