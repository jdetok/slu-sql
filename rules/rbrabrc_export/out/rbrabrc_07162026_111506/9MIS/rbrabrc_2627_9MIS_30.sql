-- M1 (LOOK FOR APPLICATION TO PM WITHIN THE AID YEAR)
SELECT RORALGS_AMT, b.SARAPPD_APDC_CODE
FROM SARADAP a
CROSS JOIN RORALGS
INNER JOIN SARAPPD b 
    ON b.SARAPPD_PIDM = a.SARADAP_PIDM
    AND b.SARAPPD_APPL_NO = a.SARADAP_APPL_NO
    AND b.SARAPPD_TERM_CODE_ENTRY = a.SARADAP_TERM_CODE_ENTRY
INNER JOIN STVAPDC c 
    ON c.STVAPDC_CODE = b.SARAPPD_APDC_CODE
    AND c.STVAPDC_INST_ACC_IND = 'Y'
    AND c.STVAPDC_SIGNF_IND = 'Y'
WHERE RORALGS_KEY_1 = 'PBDG'
AND RORALGS_KEY_4 = '9MIS'
AND CASE
	WHEN a.SARADAP_LEVL_CODE = 'PM' THEN 'PM'
END = RORALGS_KEY_5
AND RORALGS_KEY_11 = 'M1'
AND a.SARADAP_TERM_CODE_ENTRY = (
  SELECT MAX(z.SARADAP_TERM_CODE_ENTRY)
  FROM SARADAP z, ROBINST
  WHERE z.SARADAP_PIDM = a.SARADAP_PIDM
  AND z.SARADAP_TERM_CODE_ENTRY >= (ROBINST_AIDY_END_YEAR || '00')
  AND z.SARADAP_TERM_CODE_ENTRY <= :PERIOD
  AND ROBINST_AIDY_CODE = :AIDY
  AND EXISTS (
      SELECT 1
      FROM SARAPPD p, STVAPDC c
      WHERE p.SARAPPD_PIDM = z.SARADAP_PIDM
      AND p.SARAPPD_APPL_NO = z.SARADAP_APPL_NO
      AND p.SARAPPD_TERM_CODE_ENTRY = z.SARADAP_TERM_CODE_ENTRY
      AND c.STVAPDC_CODE = p.SARAPPD_APDC_CODE
      AND c.STVAPDC_INST_ACC_IND = 'Y'
      AND c.STVAPDC_SIGNF_IND = 'Y'
  )
)
AND a.SARADAP_APPL_NO = (
    select max(x.saradap_appl_no)
    from saradap x
    where x.saradap_pidm = a.saradap_pidm
    and x.saradap_term_code_entry = a.saradap_term_code_entry
)
-- max application decision code sequence number
AND b.SARAPPD_SEQ_NO = (
    SELECT MAX(y.SARAPPD_SEQ_NO)
    FROM SARAPPD y
    WHERE y.SARAPPD_PIDM = b.SARAPPD_PIDM
    AND y.SARAPPD_APPL_NO = b.SARAPPD_APPL_NO
    AND y.SARAPPD_SEQ_NO < 99
    AND y.SARAPPD_TERM_CODE_ENTRY = b.SARAPPD_TERM_CODE_ENTRY
)  
AND RORALGS_AIDY_CODE = :AIDY
