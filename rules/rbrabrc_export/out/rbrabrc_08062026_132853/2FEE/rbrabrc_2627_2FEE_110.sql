-- SPS no SGASTDN
SELECT CASE 
    -- BOTH PARTS OF TERM GET FULL
    WHEN ( -- both PS1 AND PS2        
        EXISTS (
            SELECT 'X' FROM SFRSTCR
            WHERE SFRSTCR_PIDM = a.SARADAP_PIDM
            AND SFRSTCR_TERM_CODE = :PERIOD
            AND SFRSTCR_PTRM_CODE = 'PS1'
            AND SFRSTCR_BILL_HR > '0'
        )
        AND EXISTS (
            SELECT 'X' FROM SFRSTCR
            WHERE SFRSTCR_PIDM = a.SARADAP_PIDM
            AND SFRSTCR_TERM_CODE = :PERIOD
            AND SFRSTCR_PTRM_CODE = 'PS2'
            AND SFRSTCR_BILL_HR > '0'
        )
    ) OR EXISTS ( -- ONLY PSF
            SELECT 'X' FROM SFRSTCR
            WHERE SFRSTCR_PIDM = a.SARADAP_PIDM
            AND SFRSTCR_TERM_CODE = :PERIOD
            AND SFRSTCR_PTRM_CODE = 'PSF'
            AND SFRSTCR_BILL_HR > '0'
    ) OR EXISTS ( -- ONLY 1
            SELECT 'X' FROM SFRSTCR
            WHERE SFRSTCR_PIDM = a.SARADAP_PIDM
            AND SFRSTCR_TERM_CODE = :PERIOD
            AND SFRSTCR_PTRM_CODE = '1'
            AND SFRSTCR_BILL_HR > '0'    
    ) THEN RORALGS_AMT
    -- ONLY ONE PART OF TERM GETS HALF
    WHEN EXISTS (
        SELECT 'X' FROM SFRSTCR
        WHERE SFRSTCR_PIDM = a.SARADAP_PIDM
        AND SFRSTCR_TERM_CODE = :PERIOD
        AND SFRSTCR_PTRM_CODE in ('PS1', 'PS2') -- FINDS PS1 OR PS2
        AND SFRSTCR_BILL_HR > '0'
    ) THEN RORALGS_AMT / 2
    ELSE RORALGS_AMT
END
FROM SARADAP a
inner join RORALGS on RORALGS_AIDY_CODE = :AIDY
    and RORALGS_KEY_1 = 'PBDG' 
    and RORALGS_KEY_4 = '2FEE'
    and RORALGS_KEY_7 = a.SARADAP_COLL_CODE_1 
INNER JOIN SARAPPD b
    ON b.SARAPPD_PIDM = a.SARADAP_PIDM
    AND b.SARAPPD_TERM_CODE_ENTRY = a.SARADAP_TERM_CODE_ENTRY
    AND b.SARAPPD_APPL_NO = a.SARADAP_APPL_NO 
INNER JOIN STVAPDC c
    ON c.STVAPDC_CODE = b.SARAPPD_APDC_CODE
INNER JOIN ROBINST r
    ON r.ROBINST_AIDY_CODE = :AIDY
AND a.SARADAP_TERM_CODE_ENTRY = (
    SELECT MAX(SARADAP_TERM_CODE_ENTRY)
    FROM SARADAP
    WHERE SARADAP_PIDM = a.SARADAP_PIDM
    AND SARADAP_TERM_CODE_ENTRY <= :PERIOD
)
AND b.SARAPPD_SEQ_NO = (
    SELECT MAX (SARAPPD_SEQ_NO)
    FROM SARAPPD
    WHERE SARAPPD_PIDM = b.SARAPPD_PIDM
    AND SARAPPD_SEQ_NO < 99
    AND SARAPPD_TERM_CODE_ENTRY >= (r.ROBINST_AIDY_END_YEAR || '00')
    AND SARAPPD_TERM_CODE_ENTRY <= :PERIOD
    AND SARAPPD_APPL_NO = b.SARAPPD_APPL_NO
) 
-- EXCLUDE GLOBAL GRADS
AND a.SARADAP_PIDM NOT IN (
    SELECT SGRSATT_PIDM
    FROM SGRSATT
    WHERE SGRSATT_ATTS_CODE IN ('GG2','GG3','GG4','GG5','GG6')
    AND SGRSATT_TERM_CODE_EFF = (
        SELECT MAX(z.SGRSATT_TERM_CODE_EFF)
        FROM SGRSATT z
        WHERE z.SGRSATT_PIDM = SGRSATT_PIDM
        AND z.SGRSATT_TERM_CODE_EFF <= a.SARADAP_TERM_CODE_ENTRY
    )
)
