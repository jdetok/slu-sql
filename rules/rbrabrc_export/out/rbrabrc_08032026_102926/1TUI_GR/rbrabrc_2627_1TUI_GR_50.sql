--GRAD ATHT12 WITH SGASTDN
SELECT RORALGS_AMT
FROM SGBSTDN a, SGRCHRT b, RORALGS, ROBINST
WHERE RORALGS_KEY_1 = 'PBDG'

AND RORALGS_KEY_4 = '1TUI' -- budget component

AND CASE -- level code
    WHEN a.SGBSTDN_LEVL_CODE = 'GR' THEN 'GR'
END = RORALGS_KEY_5

AND CASE -- campus code
    WHEN a.SGBSTDN_CAMP_CODE = 'FR' THEN 'FR'
END = RORALGS_KEY_6

AND CASE -- college code
    WHEN a.SGBSTDN_COLL_CODE_1 = 'AH' THEN 'AH'
END = RORALGS_KEY_7

AND CASE -- major/program code
    WHEN a.SGBSTDN_PROGRAM_1 = 'ATHT12' THEN 'ATHT12'
    WHEN a.SGBSTDN_PROGRAM_1 = 'ATHT13' THEN 'ATHT13'
END = RORALGS_KEY_9	

AND CASE -- cohort code
    WHEN b.SGRCHRT_CHRT_CODE = (ROBINST_AIDY_START_YEAR || 'AT') THEN (ROBINST_AIDY_START_YEAR || 'AT')              --2025 FOR FY26
	WHEN b.SGRCHRT_CHRT_CODE = (ROBINST_AIDY_END_YEAR || 'AT') THEN (ROBINST_AIDY_END_YEAR || 'AT')                  --2026 FOR FY26
END = RORALGS_KEY_11	

		-- max cohort term <= passed period
AND b.SGRCHRT_TERM_CODE_EFF = (
    SELECT MAX(Y.SGRCHRT_TERM_CODE_EFF)
    FROM SGRCHRT Y
    WHERE Y.SGRCHRT_PIDM = b.SGRCHRT_PIDM
    AND Y.SGRCHRT_TERM_CODE_EFF <= :PERIOD
)
-- maa.SGBSTDN term <= passed period
AND a.SGBSTDN_TERM_CODE_EFF = (
    SELECT MAX(Y.SGBSTDN_TERM_CODE_EFF)
    FROM SGBSTDN Y
    WHERE Y.SGBSTDN_PIDM = a.SGBSTDN_PIDM
    AND Y.SGBSTDN_TERM_CODE_EFF <= :PERIOD
)
AND NOT EXISTS (
    SELECT 1
    FROM SARADAP
    INNER JOIN SARAPPD
        ON SARAPPD_PIDM = SARADAP_PIDM
        AND SARAPPD_APPL_NO = SARADAP_APPL_NO
        AND SARAPPD_TERM_CODE_ENTRY = SARADAP_TERM_CODE_ENTRY
    INNER JOIN STVAPDC
        ON STVAPDC_CODE = SARAPPD_APDC_CODE
        AND STVAPDC_INST_ACC_IND = 'Y'
        AND STVAPDC_SIGNF_IND = 'Y'
    WHERE SARADAP_PIDM = a.SGBSTDN_PIDM
    AND SARADAP_TERM_CODE_ENTRY > a.SGBSTDN_TERM_CODE_EFF 
    AND SARADAP_TERM_CODE_ENTRY <= ('20' || cast(substr(:AIDY, 3, 2) as int) + 1 || '00')
    AND SARADAP_PROGRAM_1 <> a.SGBSTDN_PROGRAM_1
)
AND a.SGBSTDN_STST_CODE IN  ('AS','IL','P1')
AND a.SGBSTDN_PIDM = b.SGRCHRT_PIDM
-- AND a.SGBSTDN_PIDM = :PIDM
AND RORALGS_AIDY_CODE = ROBINST_AIDY_CODE
AND RORALGS_AIDY_CODE = :AIDY