--UG PS COLLEGE ENROLLED 
SELECT CASE
    WHEN NVL(ROKMISC.F_CALC_STUD_BILL_HRS(:PERIOD, X.SGBSTDN_PIDM, 'N'), 0) > 0
        THEN round(roralgs_amt * NVL(ROKMISC.F_CALC_STUD_BILL_HRS(:PERIOD, X.SGBSTDN_PIDM, 'N'), 0))
    END as calc_amt
FROM SGBSTDN X, SGRSATT, RORALGS
-- inner join sfs_utility.pbdg_cutoff_dates on period = :PERIOD and sysdate >= cutoff
WHERE RORALGS_KEY_1 = 'PBDG'

AND RORALGS_KEY_4 = '1TUI' -- budget component

AND CASE -- level code
    WHEN X.SGBSTDN_LEVL_CODE = 'UG' THEN 'UG'
END = RORALGS_KEY_5

AND CASE -- campus code
    WHEN X.SGBSTDN_CAMP_CODE = 'FR' THEN 'FR'
END = RORALGS_KEY_6

AND CASE -- college code
    WHEN X.SGBSTDN_COLL_CODE_1 = 'PS' THEN 'PS'
END = RORALGS_KEY_7

AND RORALGS_KEY_9 IS NULL
AND CASE 
    WHEN SGRSATT_ATTS_CODE = 'PSMV' THEN 'PSMV' 
    WHEN SGRSATT_ATTS_CODE = 'PS15' THEN 'PS15' 
END = RORALGS_KEY_10
AND RORALGS_KEY_11 IS NULL

-- max sgbstdn term <= passed period
AND X.SGBSTDN_TERM_CODE_EFF = (
    SELECT MAX(Y.SGBSTDN_TERM_CODE_EFF)
    FROM SGBSTDN Y
    WHERE Y.SGBSTDN_PIDM = X.SGBSTDN_PIDM
    AND Y.SGBSTDN_TERM_CODE_EFF <= :PERIOD
)

AND SGRSATT_TERM_CODE_EFF = (
SELECT MAX(Y.SGRSATT_TERM_CODE_EFF)
    FROM SGRSATT Y
    WHERE Y.SGRSATT_TERM_CODE_EFF <= :PERIOD
	AND Y.SGRSATT_PIDM =  SGRSATT_PIDM
)
AND X.SGBSTDN_STST_CODE IN  ('AS','IL','P1')
-- AND X.SGBSTDN_PIDM = :PIDM
AND SGRSATT_PIDM = X.SGBSTDN_PIDM
AND RORALGS_AIDY_CODE = :AIDY
-- END