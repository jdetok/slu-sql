SELECT DISTINCT(RCRAPP1_PIDM)
  FROM RCRAPP1,  RCRAPP3, ROBNYUD, SARADAP, STVAPDC, RNVAND0, RBRAPBG
  WHERE RCRAPP1_AIDY_CODE = :AIDY                            
        AND RCRAPP1_PIDM = (select spriden_pidm from spriden where spriden_change_ind is null and spriden_id = '001500766')                           
        AND RCRAPP1_CURR_REC_IND = 'Y'
        AND RCRAPP1_INFC_CODE = 'EDE'
        AND RBRAPBG_PBGP_CODE = 'UG'
        AND  RBRAPBG_RUN_NAME = 'ACTUAL'
        AND RCRAPP1_PIDM = RBRAPBG_PIDM
        AND RCRAPP1_AIDY_CODE = RBRAPBG_AIDY_CODE
--
        AND RCRAPP3_PIDM = RCRAPP1_PIDM
        AND RCRAPP3_AIDY_CODE = RCRAPP1_AIDY_CODE
        AND RCRAPP3_INFC_CODE = RCRAPP1_INFC_CODE
        AND RCRAPP3_SEQ_NO = RCRAPP1_SEQ_NO
        AND RCRAPP3_OFFL_UNOFFL_IND = '1'
        AND NVL(RCRAPP3_YR_IN_COLL_2,'X') NOT IN ('4')
        AND NVL(RCRAPP3_GRAD_OR_PROF,'X') <> '1'
--
        AND RNVAND0_PIDM = RCRAPP1_PIDM
        AND RNVAND0_AIDY_CODE = RCRAPP1_AIDY_CODE
        AND RNVAND0_GROSS_NEED < 1
--
        AND ROBNYUD_PIDM =  rcrapp1_pidm                           
        AND SUBSTR(ROBNYUD_VALUE_27,0,4) = '20' || SUBSTR(RCRAPP1_AIDY_CODE, 3, 2) 
        AND SARADAP_PIDM = rcrapp1_pidm                             
        AND SARADAP_STYP_CODE IN ('1','F')
        AND (SUBSTR(SARADAP_TERM_CODE_ENTRY,0,4) = '20' || SUBSTR(RCRAPP1_AIDY_CODE, 3, 2)
          OR SUBSTR(SARADAP_TERM_CODE_ENTRY,3,4) = SUBSTR(RCRAPP1_AIDY_CODE, 3,2) || '00')