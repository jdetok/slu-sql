SELECT DISTINCT(RORSTAT_PIDM)
FROM RORSTAT
JOIN ROBINST on ROBINST_AIDY_CODE = RORSTAT_AIDY_CODE
WHERE NOT EXISTS ( 
    SELECT 1
	FROM SFRSTCR
    WHERE SFRSTCR_PIDM = RORSTAT_PIDM
    AND SFRSTCR_CREDIT_HR > 0
    AND SFRSTCR_TERM_CODE BETWEEN (ROBINST_AIDY_END_YEAR || '00') AND ((TO_NUMBER(ROBINST_AIDY_END_YEAR)+1) || '00')
) AND (
    EXISTS (
        SELECT 1
        FROM SARADAP a
        JOIN SARAPPD b on b.SARAPPD_PIDM = a.SARADAP_PIDM
            AND b.SARAPPD_APPL_NO = a.SARADAP_APPL_NO
            AND b.SARAPPD_TERM_CODE_ENTRY = a.SARADAP_TERM_CODE_ENTRY
        JOIN STVAPDC c ON c.STVAPDC_CODE = b.SARAPPD_APDC_CODE
        WHERE a.SARADAP_PIDM = RORSTAT_PIDM
        AND (STVAPDC_APPL_INACT = 'Y' OR STVAPDC_REJECT_IND = 'Y') 
        AND SARADAP_TERM_CODE_ENTRY = (
            SELECT MAX (SARADAP_TERM_CODE_ENTRY)
            FROM SARADAP Y
            WHERE Y.SARADAP_PIDM = a.SARADAP_PIDM
            AND Y.SARADAP_TERM_CODE_ENTRY BETWEEN (ROBINST_AIDY_END_YEAR || '00') AND ((TO_NUMBER(ROBINST_AIDY_END_YEAR)+1) || '00')
        ) 
        AND b.SARAPPD_APDC_DATE = (
            SELECT MAX (Y.SARAPPD_APDC_DATE)
            FROM SARAPPD Y
            WHERE Y.SARAPPD_PIDM = b.SARAPPD_PIDM
            AND Y.SARAPPD_TERM_CODE_ENTRY BETWEEN (ROBINST_AIDY_END_YEAR || '00') AND ((TO_NUMBER(ROBINST_AIDY_END_YEAR)+1) || '00')
            AND Y.SARAPPD_APPL_NO = a.SARADAP_APPL_NO
        )
    ) AND NOT EXISTS (
        SELECT 1
        FROM SARADAP a
        JOIN SARAPPD b on b.SARAPPD_PIDM = a.SARADAP_PIDM
            AND b.SARAPPD_APPL_NO = a.SARADAP_APPL_NO
            AND b.SARAPPD_TERM_CODE_ENTRY = a.SARADAP_TERM_CODE_ENTRY
        JOIN STVAPDC c ON c.STVAPDC_CODE = b.SARAPPD_APDC_CODE
            AND STVAPDC_INST_ACC_IND = 'Y'
            AND STVAPDC_SIGNF_IND = 'Y'
        -- WHERE a.SARADAP_PIDM = RORSTAT_PIDM
        WHERE a.SARADAP_PIDM = 1502563
        AND (STVAPDC_APPL_INACT = 'Y' OR STVAPDC_REJECT_IND = 'Y') 
        AND SARADAP_TERM_CODE_ENTRY = (
            SELECT MAX (SARADAP_TERM_CODE_ENTRY)
            FROM SARADAP Y
            WHERE Y.SARADAP_PIDM = a.SARADAP_PIDM
            AND Y.SARADAP_TERM_CODE_ENTRY BETWEEN (ROBINST_AIDY_END_YEAR || '00') AND ((TO_NUMBER(ROBINST_AIDY_END_YEAR)+1) || '00')
        ) 
        AND b.SARAPPD_APDC_DATE = (
            SELECT MAX (Y.SARAPPD_APDC_CODE)
            FROM SARAPPD Y
            WHERE Y.SARAPPD_PIDM = b.SARAPPD_PIDM
            AND Y.SARAPPD_TERM_CODE_ENTRY BETWEEN (ROBINST_AIDY_END_YEAR || '00') AND ((TO_NUMBER(ROBINST_AIDY_END_YEAR)+1) || '00')
            AND Y.SARAPPD_APPL_NO = a.SARADAP_APPL_NO
        )
    )
)
AND RORSTAT_AIDY_CODE = :AIDY
